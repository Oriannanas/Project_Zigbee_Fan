#include "esp_log.h"
#include "driver/ledc.h"
#include "light_driver.h"

static bool s_power;
static uint8_t s_level;

static void light_driver_apply_output(void)
{
    const uint32_t duty = s_power ? s_level : 0;
    ESP_ERROR_CHECK(ledc_set_duty(LEDC_LOW_SPEED_MODE, LEDC_CHANNEL_0, duty));
    ESP_ERROR_CHECK(ledc_update_duty(LEDC_LOW_SPEED_MODE, LEDC_CHANNEL_0));
}

void light_driver_set_power(bool power)
{
    s_power = power;
    light_driver_apply_output();
}

void light_driver_set_level(uint8_t level)
{
    s_level = level;
    light_driver_apply_output();
}

void light_driver_init(bool power, uint8_t level)
{
    ledc_timer_config_t ledc_timer = {
        .speed_mode = LEDC_LOW_SPEED_MODE,
        .duty_resolution = LEDC_TIMER_8_BIT,
        .timer_num = LEDC_TIMER_0,
        .freq_hz = LIGHT_PWM_FREQUENCY_HZ,
        .clk_cfg = LEDC_AUTO_CLK,
    };
    ledc_channel_config_t ledc_channel = {
        .gpio_num = LIGHT_OUTPUT_GPIO,
        .speed_mode = LEDC_LOW_SPEED_MODE,
        .channel = LEDC_CHANNEL_0,
        .intr_type = LEDC_INTR_DISABLE,
        .timer_sel = LEDC_TIMER_0,
        .duty = 0,
        .hpoint = 0,
    };

    ESP_ERROR_CHECK(ledc_timer_config(&ledc_timer));
    ESP_ERROR_CHECK(ledc_channel_config(&ledc_channel));

    s_level = level;
    s_power = power;
    light_driver_apply_output();
}
